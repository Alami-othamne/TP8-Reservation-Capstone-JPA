CREATE TABLE IF NOT EXISTS utilisateurs (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nom VARCHAR(120) NOT NULL CHECK (LENGTH(TRIM(nom)) > 0),
 email VARCHAR(254) NOT NULL CHECK (LENGTH(TRIM(email)) > 0),
 version INT NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS salles (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nom VARCHAR(120) NOT NULL CHECK (LENGTH(TRIM(nom)) > 0),
 capacite INT NOT NULL CHECK (capacite > 0), version INT NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS reservations (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 utilisateur_id BIGINT NOT NULL REFERENCES utilisateurs(id),
 salle_id BIGINT NOT NULL REFERENCES salles(id),
 date_debut TIMESTAMP NOT NULL, date_fin TIMESTAMP NOT NULL,
 version INT NOT NULL DEFAULT 0, CHECK (date_fin > date_debut)
);
CREATE INDEX IF NOT EXISTS ix_reservation_salle_dates ON reservations(salle_id, date_debut, date_fin);
CREATE INDEX IF NOT EXISTS ix_reservation_utilisateur ON reservations(utilisateur_id);
